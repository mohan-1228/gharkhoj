/**
 * Generates a SQL data migration with the launch cities, neighbourhoods and
 * amenities so every environment (incl. production) gets reference data via
 * `prisma migrate deploy` — no seed script needed in prod.
 * Usage: pnpm tsx scripts/gen-reference-migration.ts > prisma/migrations/<ts>_reference_data/migration.sql
 */
import { AMENITIES, CITIES } from "../prisma/seed/data";
import { slugify } from "../src/lib/format";

const q = (s: string | undefined | null) => (s == null ? "NULL" : `'${s.replace(/'/g, "''")}'`);
const out: string[] = ["-- Reference data (generated by scripts/gen-reference-migration.ts). Idempotent.", ""];

for (const a of AMENITIES) {
  out.push(
    `INSERT INTO amenities (code, label, label_ne, category, icon) VALUES (${q(a.code)}, ${q(a.label)}, ${q(a.labelNe)}, '${a.category}', ${q(a.icon)}) ON CONFLICT (code) DO NOTHING;`,
  );
}
out.push("");
for (const c of CITIES) {
  out.push(
    `INSERT INTO cities (name, name_ne, slug, province, district, centroid, is_active) VALUES (${q(c.name)}, ${q(c.nameNe)}, ${q(c.slug)}, ${q(c.province)}, ${q(c.district)}, ST_SetSRID(ST_MakePoint(${c.lng}, ${c.lat}), 4326)::geography, true) ON CONFLICT (slug) DO NOTHING;`,
  );
  for (const n of c.neighborhoods) {
    out.push(
      `INSERT INTO neighborhoods (city_id, name, name_ne, slug, centroid) SELECT id, ${q(n.name)}, ${q(n.nameNe)}, ${q(slugify(n.name))}, ST_SetSRID(ST_MakePoint(${n.lng}, ${n.lat}), 4326)::geography FROM cities WHERE slug = ${q(c.slug)} ON CONFLICT (city_id, slug) DO NOTHING;`,
    );
  }
}
console.log(out.join("\n"));
