import Link from "next/link";
import { BadgeCheck, Bath, BedDouble, MapPin, Ruler } from "lucide-react";
import { PROPERTY_TYPE_LABELS, type PropertyTypeValue } from "@/lib/constants";
import { formatNpr, formatSqft } from "@/lib/format";
import type { ListingCardData } from "@/server/services/search-service";
import type { ReactNode } from "react";

/** Search result card. Uses pre-generated WebP variants with srcset for low-bandwidth phones. */
export function ListingCard({
  listing,
  priority = false,
  action,
}: {
  listing: ListingCardData;
  priority?: boolean;
  action?: ReactNode;
}) {
  const place = [listing.neighborhood?.name, listing.city.name].filter(Boolean).join(", ");
  return (
    <article className="group bg-card relative overflow-hidden rounded-xl border shadow-xs transition hover:shadow-md">
      <div className="bg-muted relative aspect-[3/2]">
        {listing.image ? (
          // eslint-disable-next-line @next/next/no-img-element -- variants pre-generated by the image pipeline
          <img
            src={listing.image.md}
            srcSet={`${listing.image.sm} 320w, ${listing.image.md} 640w`}
            sizes="(min-width: 1024px) 33vw, (min-width: 640px) 50vw, 100vw"
            alt={listing.title}
            loading={priority ? "eager" : "lazy"}
            fetchPriority={priority ? "high" : "auto"}
            decoding="async"
            className="size-full object-cover"
          />
        ) : (
          <div className="text-muted-foreground flex size-full items-center justify-center text-sm">No photo yet</div>
        )}
        <span className="bg-background/90 absolute top-2 left-2 rounded-md px-2 py-0.5 text-xs font-medium">
          {PROPERTY_TYPE_LABELS[listing.propertyType as PropertyTypeValue]}
        </span>
        {action && <div className="absolute top-2 right-2 z-10">{action}</div>}
      </div>
      <div className="space-y-1.5 p-3">
        <p className="text-lg font-bold">
          {formatNpr(listing.rentNpr)}
          <span className="text-muted-foreground text-sm font-normal"> / month</span>
          {listing.negotiable && <span className="ml-2 text-xs font-normal text-emerald-700">Negotiable</span>}
        </p>
        <h3 className="line-clamp-1 font-medium">
          <Link href={`/listing/${listing.slug}`} className="after:absolute after:inset-0 focus-visible:outline-none">
            {listing.title}
          </Link>
        </h3>
        <p className="text-muted-foreground flex items-center gap-1 text-sm">
          <MapPin className="size-3.5 shrink-0" aria-hidden />
          <span className="truncate">{place}</span>
          {listing.distanceKm != null && <span className="shrink-0">· {listing.distanceKm} km</span>}
        </p>
        <ul className="text-muted-foreground flex flex-wrap gap-x-3 gap-y-1 text-sm">
          <li className="flex items-center gap-1">
            <BedDouble className="size-4" aria-hidden />
            {listing.bedrooms === 0 ? "Studio" : `${listing.bedrooms} bed`}
          </li>
          <li className="flex items-center gap-1">
            <Bath className="size-4" aria-hidden />
            {listing.bathrooms} bath
          </li>
          {listing.areaSqft && (
            <li className="flex items-center gap-1">
              <Ruler className="size-4" aria-hidden />
              {formatSqft(listing.areaSqft)}
            </li>
          )}
          {listing.landlordVerified && (
            <li className="flex items-center gap-1 text-emerald-700">
              <BadgeCheck className="size-4" aria-hidden /> Verified
            </li>
          )}
        </ul>
      </div>
    </article>
  );
}
