import type { NextConfig } from "next";
import createNextIntlPlugin from "next-intl/plugin";

const withNextIntl = createNextIntlPlugin("./src/i18n/request.ts");

const mediaOrigin = (() => {
  try {
    return new URL(process.env.MEDIA_BASE_URL ?? "http://localhost:9000").origin;
  } catch {
    return "http://localhost:9000";
  }
})();
const s3Origin = process.env.S3_PUBLIC_ENDPOINT ? new URL(process.env.S3_PUBLIC_ENDPOINT).origin : "";
const isDev = process.env.NODE_ENV !== "production";

/** Content-Security-Policy: no inline scripts from third parties; tiles from OSM; media from CloudFront/MinIO. */
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  `img-src 'self' data: blob: ${mediaOrigin} https://*.tile.openstreetmap.org https://tile.openstreetmap.org`,
  "font-src 'self' data:",
  `connect-src 'self' ${s3Origin} https://*.amazonaws.com ${mediaOrigin}`.trim(),
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self' https://*.amazoncognito.com",
  "object-src 'none'",
].join("; ");

const nextConfig: NextConfig = {
  output: "standalone", // minimal server bundle for the Docker image (ECS Fargate)
  poweredByHeader: false,
  reactStrictMode: true,
  serverExternalPackages: ["sharp", "pino", "pino-pretty"],
  images: {
    // Variants are pre-generated by the image pipeline, so Next's optimizer is not needed.
    unoptimized: true,
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(self)" },
          ...(isDev
            ? []
            : [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" }]),
        ],
      },
    ];
  },
};

export default withNextIntl(nextConfig);
